      ('inverseSurface', s.inverseSurface),
      ('onInverseSurface', s.onInverseSurface),
      ('inversePrimary', s.inversePrimary),
      ('surfaceTint', s.surfaceTint),
    ];

String _hex(Color c) =>
    '0x${c.toARGB32().toRadixString(16).padLeft(8, '0').toUpperCase()}';

String _scheme(String name, ColorScheme s) {
  final b = StringBuffer()
    ..writeln('  static const ColorScheme $name = ColorScheme(')
    ..writeln('    brightness: Brightness.${s.brightness.name},');
  for (final (role, color) in schemeRoles(s)) {
    b.writeln('    $role: Color(${_hex(color)}),');
  }
  b.writeln('  );');
  return b.toString();
}

/// A plain, dependency-free `app_theme.dart` for [theme].
/// Paste it into `lib/` and use `AppTheme.light()` / `AppTheme.dark()`.
String exportThemeDart(ReskinTheme theme, {String className = 'AppTheme'}) {
  String font(String? f) =>
      f == null ? 'null' : "'${f.replaceAll("'", r"\'")}'";
  final r = theme.radius == theme.radius.roundToDouble()
      ? theme.radius.toStringAsFixed(1)
      : theme.radius.toString();
  return """
// Generated by reskin (https://github.com/AbdAlftahSalem/reskin)
// Theme: ${theme.name.replaceAll('\n', ' ')}${theme.prompt != null ? '  ·  prompt: "${theme.prompt!.replaceAll('\n', ' ')}"' : ''}
// Contrast: every on*/background pair checked against WCAG AA (4.5:1).
import 'package:flutter/material.dart';

class $className {
  $className._();

  static const double radius = $r;
  static const String${theme.headingFont == null ? '?' : ''} headingFont = ${font(theme.headingFont)};
  static const String${theme.bodyFont == null ? '?' : ''} bodyFont = ${font(theme.bodyFont)};

${_scheme('lightScheme', theme.light)}
${_scheme('darkScheme', theme.dark)}
  static ThemeData light() => _build(lightScheme);
  static ThemeData dark() => _build(darkScheme);

  static ThemeData _build(ColorScheme scheme) {
    final shape = RoundedRectangleBorder(
      borderRadius: BorderRadius.circular(radius),
    );
    final base = ThemeData(
      useMaterial3: true,
      colorScheme: scheme,
      fontFamily: bodyFont,
    );
    final text = base.textTheme;
    TextStyle? h(TextStyle? s) => s?.copyWith(fontFamily: headingFont);
    return base.copyWith(
      textTheme: headingFont == null
          ? text
          : text.copyWith(
              displayLarge: h(text.displayLarge),
              displayMedium: h(text.displayMedium),
              displaySmall: h(text.displaySmall),
              headlineLarge: h(text.headlineLarge),
              headlineMedium: h(text.headlineMedium),
              headlineSmall: h(text.headlineSmall),
              titleLarge: h(text.titleLarge),
            ),
      cardTheme: CardThemeData(shape: shape, clipBehavior: Clip.antiAlias),
      filledButtonTheme: FilledButtonThemeData(
        style: FilledButton.styleFrom(shape: shape),
      ),
      elevatedButtonTheme: ElevatedButtonThemeData(
        style: ElevatedButton.styleFrom(shape: shape),
      ),
      outlinedButtonTheme: OutlinedButtonThemeData(
        style: OutlinedButton.styleFrom(shape: shape),
      ),
      chipTheme: ChipThemeData(shape: shape),
      dialogTheme: DialogThemeData(shape: shape),
      inputDecorationTheme: InputDecorationTheme(
        border: OutlineInputBorder(
          borderRadius: BorderRadius.circular(radius),
        ),
      ),
    );
  }
}
""";
}
